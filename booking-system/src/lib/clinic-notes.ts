/**
 * 這筆預約是否適用「平日午診 18:00 前返回報到」。
 * 只有週一至週五的午診有這個時限；週六午診、早診、晚診是「看完最後一位病人前」，不另外提醒。
 */
export function isWeekdayAfternoon(
  dateStr: string,
  session: "MORNING" | "AFTERNOON" | "EVENING" | undefined,
): boolean {
  if (!dateStr || session !== "AFTERNOON") return false;
  const wd = weekdayOf(dateStr);
  return wd >= 1 && wd <= 5;
}

